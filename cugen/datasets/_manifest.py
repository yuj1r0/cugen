_ZENODO_6522639 = "https://zenodo.org/api/records/6522639/files/{}/content"


def _zenodo(name, size, md5, sha256):
    return dict(name=name, urls=[_ZENODO_6522639.format(name)], size=size, md5=md5, sha256=sha256)


